// of k nodes spreads them over 90°, so the arc between two of them is
// R·(π/2)/(k+1) and must clear NODE_SIZE. Economy's Ancient ring (8 techs + a
// TBD, at the smallest radius) is the binding constraint; `validateStructure`
// checks every ring, so shrink these only if the sim still passes.
export const RING0 = 520
export const RING_STEP = 215
export const NODE_SIZE = 72 // hexagon width in content px

export const ringRadius = (ring) => RING0 + ring * RING_STEP
const rad = (deg) => (deg * Math.PI) / 180

export const LAID_OUT = PROGRESS_NODES.map((n) => {
  const { from, to } = QUADRANTS[n.quadrant]
  const count = TREE[n.quadrant][n.ring].length
  const angle = rad(from + (to - from) * ((n.index + 1) / (count + 1)))
  const R = ringRadius(n.ring)
  return { ...n, angle, x: Math.cos(angle) * R, y: Math.sin(angle) * R }
})

export const LAID_OUT_BY_ID = new Map(LAID_OUT.map((n) => [n.id, n]))

/** Content half-extent needed to show every ring up to `maxRing`. */
export const extentFor = (maxRing) => ringRadius(maxRing) + NODE_SIZE * 1.6

/**
 * An edge, drawn as a curve that INTERPOLATES IN POLAR SPACE — radius and angle
 * both eased from parent to child — rather than as a straight chord.
 *
 * UNUSED WHILE THE WEB HAS NO DEPENDENCIES, and kept for when it does. The rule
 * it buys: a straight chord between two rings dips inside the inner ring
 * whenever its endpoints are far apart in angle, wandering into the band below
 * and crossing edges that live there. A polar curve cannot — its radius rises
 * monotonically, so it stays in its own annulus, and at any radius it has
 * exactly ONE point, at
 *
 *     angle(t) = parentAngle + (childAngle - parentAngle) * t
 *
 * Linear interpolation preserves order, so two edges of one band whose parent
 * angles and child angles are BOTH non-decreasing can never swap sides.
 */
export function edgePoints(parent, child, steps = 14) {
  const out = []
  const r0 = ringRadius(parent.ring)
  const r1 = ringRadius(child.ring)
  for (let i = 0; i <= steps; i++) {
    const t = i / steps
    const r = r0 + (r1 - r0) * t
    const a = parent.angle + (child.angle - parent.angle) * t
    out.push([Math.cos(a) * r, Math.sin(a) * r])
  }
  return out
}

/** The same curve as an SVG path string. */
export const edgePath = (parent, child) =>
  edgePoints(parent, child).map(([x, y], i) => `${i ? 'L' : 'M'}${x.toFixed(1)} ${y.toFixed(1)}`).join(' ')

/** Arc between two neighbours of a quadrant-ring holding `count` nodes. */
export const nodeSpacing = (ring, count) => (ringRadius(ring) * Math.PI) / 2 / (count + 1)

// ---------------------------------------------------------------------------
// Structure check — run by sims/progress.mjs
// ---------------------------------------------------------------------------

/** Returns a list of structural violations (empty = good). */
export function validateStructure() {
  const v = []

  // 1. one ring per age, in every quadrant
  for (const [q, rings] of Object.entries(TREE)) {
    if (rings.length !== RING_AGES.length) {
      v.push(`${q}: has ${rings.length} rings, expected ${RING_AGES.length} (one per age)`)
    }
  }

  // 2. LEGIBILITY. Rings are ages, so they are unequal by design — but a ring
  //    can still be packed past what its circumference can show. This is the
  //    check that catches it, rather than someone noticing overlapping hexes.
  for (const [q, rings] of Object.entries(TREE)) {
    rings.forEach((ring, r) => {
      const gap = nodeSpacing(r, ring.length)
      if (gap < NODE_SIZE * 1.05) {
        v.push(`${q} ring ${r} (${RING_AGES[r]}): ${ring.length} nodes leaves only ${gap.toFixed(0)}px between them (need ${(NODE_SIZE * 1.05).toFixed(0)})`)
      }
    })
  }

  // 3. names are unique, and any prereq (there are none right now) resolves to a
  //    node one ring inside, in the same quadrant
  const seenNames = new Set()
  for (const n of PROGRESS_NODES) {
    // TBDs are generated and all read "TBD" — they are identified by position.
    if (!n.tbd) {
      if (seenNames.has(n.name)) v.push(`duplicate node name: ${n.name}`)
      seenNames.add(n.name)
    }
    for (const p of n.prereqs) {
      const pn = BY_ID.get(p)
      if (!pn) v.push(`${n.id}: unknown prereq ${p}`)
      else if (pn.ring !== n.ring - 1) v.push(`${n.id}: prereq ${p} is not in the ring inside it`)
      else if (pn.quadrant !== n.quadrant) v.push(`${n.id}: prereq ${p} is in another quadrant`)
    }
    if (n.ring === 0 && n.prereqs.length) v.push(`${n.id}: ring-0 node has prereqs`)
  }

  // 4. exclusivity: real nodes, same quadrant, same ring
  for (const g of FORK_GROUPS) {
    const nodes = g.map((id) => BY_ID.get(id))
    if (nodes.some((x) => !x)) { v.push(`exclusive group names a node that does not exist: ${g.join(', ')}`); continue }
    if (new Set(nodes.map((x) => x.ring)).size > 1) {
      v.push(`exclusive group spans rings, so one side can never be chosen against the other: ${nodes.map((x) => x.name).join(', ')}`)
    }
    if (new Set(nodes.map((x) => x.quadrant)).size > 1) v.push(`exclusive group spans quadrants: ${g.join(', ')}`)
  }

  // 5. NO CROSSED EDGES. Vacuous while there are no dependencies; kept so the
  //    rule is enforced the moment any come back. Edges are polar curves
  //    confined to their own annulus, so two cross iff their endpoint orders
  //    disagree: sort a band by parent angle and child angles must not go back.
  for (const q of Object.keys(TREE)) {
    for (let r = 1; r <= MAX_RING; r++) {
      const band = []
      for (const n of LAID_OUT) {
        if (n.quadrant !== q || n.ring !== r) continue
        for (const p of n.prereqs) {
          const pn = LAID_OUT_BY_ID.get(p)
          if (pn) band.push({ pa: pn.angle, ca: n.angle, label: `${p}->${n.id}` })
        }
      }
      band.sort((a, b) => a.pa - b.pa || a.ca - b.ca)
      for (let i = 1; i < band.length; i++) {
        if (band[i].ca < band[i - 1].ca - 1e-9) {
          v.push(`edges cross: ${band[i - 1].label} × ${band[i].label} (${q} ring ${r}: a parent's children run backwards)`)
        }
      }
    }
  }

  // 6. every ring must still offer enough attainable nodes to open the next one
  for (let r = 0; r < MAX_RING; r++) {
    const lostToForks = FORK_GROUPS
      .filter((g) => BY_ID.get(g[0])?.ring === r)
      .reduce((sum, g) => sum + g.length - 1, 0)
    const attainable = (ringRealCount[r] ?? 0) - lostToForks
    if (attainable < ringUnlock(r)) {
      v.push(`ring ${r} (${RING_AGES[r]}) offers only ${attainable} attainable nodes (< ${ringUnlock(r)})`)
    }
  }

  // 7. every referenced sub-definition exists, and any WIRED effect names
  //    something real. No unit may be unlocked twice.
  const unlockedBy = new Map()
  for (const n of PROGRESS_NODES) {
    for (const s of n.sub) if (!DEFINITIONS[s]) v.push(`${n.id}: unknown sub-definition "${s}"`)
    for (const f of n.effects) {
      if (f.kind === 'unit') {
        if (!UNIT_DEFS[f.unit]) v.push(`${n.id}: unknown unit ${f.unit}`)
        if (unlockedBy.has(f.unit)) v.push(`${f.unit} unlocked twice: ${unlockedBy.get(f.unit)} and ${n.id}`)
        unlockedBy.set(f.unit, n.id)
      }
      if (f.kind === 'troops' && !UNIT_TYPES.includes(f.type)) v.push(`${n.id}: unknown unit class ${f.type}`)
      if (f.kind === 'building' && !BUILDING_DEFS[f.building]) v.push(`${n.id}: unknown building ${f.building}`)
    }
  }
  if (unlockedBy.has('warrior')) v.push('warrior is the starting unit and must not be a node unlock')

  return v
}
