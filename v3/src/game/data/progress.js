/**
 * One node. `tag` is its headline category — it picks the icon and the "what is
 * this" line, and is the one thing here that is not free text.
 *
 *   N(name, tag, text, { sub, effects, from })
 *
 * `from` (a parent name one ring inside, same quadrant) is supported but unused
 * — see the header.
 */
const N = (name, tag, text, opts = {}) => ({
  name,
  tag,
  text,
  from: opts.from ? [].concat(opts.from) : [],
  sub: opts.sub ?? [],
  effects: opts.effects ?? [],
})

