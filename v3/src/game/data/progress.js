// The progress web (v3) — authored from the design brief.
//
// 297 techs in 320 slots: four quadrants — Society / Technology / Economy /
// Military — each growing by TWO nodes per ring, so a quadrant runs
// 3 · 5 · 7 · 9 · 11 · 13 · 15 · 17 and the eight rings hold 12 / 20 / 28 / 36 /
// 44 / 52 / 60 / 68. The 23 leftover slots are left EMPTY on purpose (`GAP`),
// two or three per ring, as room to add techs without re-shaping the web.
//
// ---------------------------------------------------------------------------
// STRUCTURE
// ---------------------------------------------------------------------------
// Rings read as ages: 0 stone · 1 bronze · 2 classical · 3 medieval ·
// 4 renaissance · 5 industrial · 6 modern/space · 7 far future.
//
// A node names its parent BY NAME (`from`), and a parent must sit in the ring
// immediately inside it, in the same quadrant. **A node may have no parent at
// all** — it then unlocks with its ring. That is what lets the web carry small
// self-contained subtrees (the fortification line, the vision ladder, the
// religion stack) instead of one giant lattice where everything descends from
// everything.
//
// EXCLUSIVITY IS EXPLICIT AND RARE (`EXCLUSIVE`). Only where the choice is a
// real historical either/or — Longbow vs Crossbow, Monotheism vs Polytheism,
// Democracy vs Communism vs Fascism. Taking one kills its partners permanently,
// and anything downstream with no other route in dies with them. Sibling nodes
// are NOT exclusive by default; branching is just branching.
//
// NO CROSSED EDGES is still a hard property, asserted by `validateStructure()`
// (`node sims/progress.mjs`). Each ring lays out in declared order, so the rule
// while authoring is: **read a ring top to bottom and the parent indices must
// never go backwards.** Parentless nodes have no edge and so constrain nothing —
// they can be slotted anywhere, which is what makes them useful as spacers.
//
// ---------------------------------------------------------------------------
// TEXT vs WIRING
// ---------------------------------------------------------------------------
// ⚠️ These nodes are DESIGN TEXT. They carry no `effects`, so taking one grants
// nothing yet — the web is a readable plan, not a working economy. The effect
// vocabulary that used to live here now lives in `effects.js`, unchanged and
// still applied by `GameManager._applyEffects`; wiring a node means attaching
// records from there to it. A node that HAS effects gets its text generated by
// `describe()` instead, so a wired node's description can never drift.
//
// Terms a node leans on (buildings it creates, rules it invents) are listed in
// `sub:` and defined once in `definitions.js`; the tooltip renders them as
// hoverable chips.

