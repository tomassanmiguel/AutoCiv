// --- Build the flat node list ----------------------------------------------
export const PROGRESS_NODES = []
const idAt = {} // quadrant -> ring -> index -> id

for (const [quadrant, rings] of Object.entries(TREE)) {
  // TBD placeholders are appended per ring rather than authored, so the count
  // is one constant instead of 84 array entries.
  rings.forEach((ring, r) => {
    for (let i = 0; i < TBD_PER_RING(r); i++) {
      ring.push(N('TBD', 'tbd', 'An empty slot. Something will go here — the ring has room.'))
    }
  })
  // TBDs all read "TBD", so their ids come from position rather than name.
  idAt[quadrant] = rings.map((ring, r) => ring.map((e, i) => (
    e.tag === 'tbd' ? `${quadrant}-tbd-${r}-${i}` : `${quadrant}-${slug(e.name)}`
  )))
  rings.forEach((ring, r) => {
    ring.forEach((entry, i) => {
      const byName = (name) => {
        const j = rings[r - 1]?.findIndex((e) => e.name === name)
        return j >= 0 ? idAt[quadrant][r - 1][j] : `MISSING:${name}`
      }
      const [icon, label] = TAG[entry.tag] ?? TAG.policy
      PROGRESS_NODES.push({
        id: idAt[quadrant][r][i],
        name: entry.name,
        // A TBD slot is drawn but can never be taken — see GameManager.progressState.
        tbd: entry.tag === 'tbd',
        effects: entry.effects,
        // A wired node describes itself from its effects; a design-text node
        // uses the text it was authored with. Never both.
        effect: entry.effects.length ? describe(entry.effects) : entry.text,
        unlocks: label,
        kind: entry.tag,
        sub: entry.sub,
        quadrant, ring: r, index: i,
        age: RING_AGES[r],
        icon,
        prereqs: entry.from.map(byName),
        excludes: [],
      })
    })
  })
}

const BY_ID = new Map(PROGRESS_NODES.map((n) => [n.id, n]))
const idOf = (quadrant, name) => `${quadrant}-${slug(name)}`

/** Real (non-TBD) nodes in a ring, across all quadrants. */
const ringRealCount = []
for (const n of PROGRESS_NODES) {
  if (n.tbd) continue
  ringRealCount[n.ring] = (ringRealCount[n.ring] ?? 0) + 1
}

/**
 * How many nodes of ring `r` must be taken before ring `r+1` appears.
 *
 * Derived from what the ring actually holds — rings are ages, so they are
 * deliberately unequal and a fixed number would be a stroll through one and a
 * wall in another.
 */
export const ringUnlock = (ring) => Math.max(4, Math.round((ringRealCount[ring] ?? 0) * 0.4))

// --- Apply the hand-listed exclusivity --------------------------------------
export const FORK_GROUPS = []
for (const [quadrant, groups] of Object.entries(EXCLUSIVE)) {
  for (const names of groups) {
    const ids = names.map((n) => idOf(quadrant, n))
    FORK_GROUPS.push(ids)
    for (const a of ids) {
      const node = BY_ID.get(a)
      if (!node) continue
      for (const b of ids) if (a !== b) node.excludes.push(b)
    }
  }
}

