// --- Build the flat node list ----------------------------------------------
export const PROGRESS_NODES = []
const idAt = {} // quadrant -> ring -> index -> id (null for a GAP)

for (const [quadrant, rings] of Object.entries(TREE)) {
  idAt[quadrant] = rings.map((ring) => ring.map((e) => (e ? `${quadrant}-${slug(e.name)}` : null)))
  rings.forEach((ring, r) => {
    ring.forEach((entry, i) => {
      if (!entry) return // GAP: the slot exists for spacing, the node does not
      const byName = (name) => {
        const j = rings[r - 1]?.findIndex((e) => e?.name === name)
        return j >= 0 ? idAt[quadrant][r - 1][j] : `MISSING:${name}`
      }
      const [icon, label] = TAG[entry.tag] ?? TAG.policy
      PROGRESS_NODES.push({
        id: idAt[quadrant][r][i],
        name: entry.name,
        effects: entry.effects,
        // A wired node describes itself from its effects; a design-text node
        // uses the text it was authored with. Never both.
        effect: entry.effects.length ? describe(entry.effects) : entry.text,
        unlocks: label,
        kind: entry.tag,
        sub: entry.sub,
        quadrant, ring: r, index: i,
        icon,
        prereqs: entry.from.map(byName),
        excludes: [],
      })
    })
  })
}

